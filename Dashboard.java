    private void BtnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnTambahActionPerformed
        // TODO add your handling code here:
        String kode= txtKodeBuku.getText();
        String judul= txtJudulBuku.getText();
        String penulis= txtPenulis.getText();
        String tahun= txtTahunTerbit.getText();
        
        String genre = "";
        if (RbRomance.isSelected()) { 
            genre = "Romance";
        } else if (RbFiksi.isSelected()) { 
            genre = "Fiksi";
        } if (RbHorror.isSelected()){
            genre = "Horror";
        }
        
        model = (DefaultTableModel) TblBuku.getModel();
        model.addRow(new Object[]{kode, judul,penulis, tahun, genre});
    }//GEN-LAST:event_BtnTambahActionPerformed

    private void BtnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnHapusActionPerformed
        // TODO add your handling code here:
        int row = TblBuku.getSelectedRow();
        
        if (row >=0){
            model=(DefaultTableModel)TblBuku.getModel();
            model.removeRow(row);
        }else {
        JOptionPane.showMessageDialog(null, "Pilihan Baris Yang Ingin Dihapus!");
        }
    }//GEN-LAST:event_BtnHapusActionPerformed

    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        // TODO add your handling code here:
        String nama= txtNamaSiswa.getText();
        String nis= txtNIS.getText();
        String kelas= txtKelas.getText();
     
        String jurusan="";
        if (RbRPL.isSelected())
            jurusan="RPL";
        else if (RbTKJ.isSelected())
            jurusan="TKJ";
        else if (RbTB.isSelected())
            jurusan ="TB";
        else if (RbANM.isSelected())
            jurusan="ANM";

        model=(DefaultTableModel)TblSiswa.getModel();
        model.addRow(new Object[]{nama,nis,kelas,jurusan});
    }//GEN-LAST:event_BtnSimpanActionPerformed

